const bytes=Buffer.from(html);receipt.legacyArtifact={...receipt.artifact};receipt.artifact={...receipt.artifact,bytes:bytes.length,sha256:hash(bytes)};
receipt.inputs.push(...[[servicePath,serviceBytes],[uiPath,uiBytes]].map(([p,b])=>({path:p,bytes:b.length,sha256:hash(b)})));
receipt.dependencyGraph.push({path:servicePath,dependencies,exports:['V2_CAPABILITIES','bindExistingV2Storage','createV2Service']});
receipt.d408Composition={kind:'explicit-isolated-v2-ui-service-localStorage',storageKey:'mytodo-d408-v2-isolated-v1',productionAdmission:false,remoteSync:false,formalSourceChanged:false,serviceRuntime:'UNVERIFIED until independent service browser acceptance'};
await fs.writeFile(artifactFile,bytes);await fs.writeFile(receiptFile,JSON.stringify(receipt,null,2)+'\n');
console.log(JSON.stringify({status:'built',sourceSha:receipt.sourceSha,artifact:receipt.artifact,composition:receipt.d408Composition}));
